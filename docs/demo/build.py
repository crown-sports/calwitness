class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.paths = []

    def handle_starttag(self, tag, attrs):
        if tag == "a":
            value = dict(attrs).get("href", "")
            if value and not value.startswith(("https://", "#")):
                self.paths.append(value)


def build() -> None:
    inputs = {
        name: (ROOT / "examples" / f"{name}.ics").read_bytes()
        for name in ("before", "after", "duplicate")
    }
    changed = compare_calendars(inputs["before"], inputs["after"], start=START, end=END)
    incomplete = compare_calendars(inputs["before"], inputs["duplicate"], start=START, end=END)
    assert changed["status"] == "changed" and changed["complete"]
    assert changed["summary"] == {
        "added": 2,
        "removed": 1,
        "moved": 1,
        "duration_changed": 2,
        "moved_and_resized": 0,
        "unchanged": 1,
        "issues": 0,
    }
    assert incomplete["status"] == "incomplete" and not incomplete["complete"]
    assert not incomplete["changes"] and incomplete["summary"]["issues"] == 1
    assert {issue["code"] for issue in incomplete["issues"]} == {"DUPLICATE_IDENTITY"}
    pages = {
        "changed.html": render_html(changed, synthetic=True),
        "incomplete.html": render_html(incomplete, synthetic=True),
        "index.html": landing(changed, incomplete),
    }
    for name, page in pages.items():
        (OUTPUT / name).write_text(page, encoding="utf-8")
    for name, report in (("changed", changed), ("incomplete", incomplete)):
        (OUTPUT / f"{name}.json").write_text(
            json.dumps(report, ensure_ascii=True, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
    (OUTPUT / "files").mkdir(exist_ok=True)
    for name, data in inputs.items():
        (OUTPUT / "files" / f"{name}.ics").write_bytes(data)
    (OUTPUT / ".nojekyll").touch()
    for page in pages.values():
        links = Links()
        links.feed(page)
        for path in links.paths:
            assert (OUTPUT / path).is_file(), f"Broken local demo link: {path}"
    print("Generated synthetic changed/incomplete HTML and JSON, index, and 3 input copies.")


if __name__ == "__main__":
    build()
